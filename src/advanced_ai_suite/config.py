"""Application settings, loaded from environment variables / .env."""

from functools import lru_cache
from typing import Literal

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings): #Class to reate a settings object that reads configuration from environment variables and a .env file.
    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )
#pydantic's BaseSettings class is used to define application settings that can be loaded from environment variables or a .env file. The SettingsConfigDict specifies the configuration for loading the settings, including the name of the .env file, its encoding, and how to handle extra fields.
    # Required: no defaults on purpose. Missing => startup fails loudly.
    ollama_base_url: str #"This app requires a text (str) setting called ollama_base_url (e.g., http://localhost:11434)."
    ollama_default_model: str #pydantic uses : type hints to define the expected data type for each setting. In this case, ollama_base_url and ollama_default_model are both expected to be strings (str).

    # Timeouts (seconds). One per phase, so a hung model can't hang us forever.
    ollama_connect_timeout_s: float = Field(default=5, gt=0) #gt means greater than, so the value must be greater than 0.
    ollama_read_timeout_s: float = Field(default=120, gt=0)
    ollama_write_timeout_s: float = Field(default=20, gt=0)
    ollama_pool_timeout_s: float = Field(default=5, gt=0)

    # Retries apply to transient connection failures only.
    ollama_max_retries: int = Field(default=2, ge=0, le=5)
    ollama_retry_wait_s: float = Field(default=0.5, ge=0) #wait 0.5 seconds before retrying a failed request.

    # Hard cap on generated tokens: local models can ramble forever.
    max_output_tokens: int = Field(default=512, ge=1, le=4096) #limits the number of tokens generated by the model to a maximum of 4096.

    log_level: Literal["DEBUG", "INFO", "WARNING", "ERROR"] = "INFO" #log_level is a setting that can only take one of four string values: "DEBUG", "INFO", "WARNING", or "ERROR". 
    #The default value is set to "INFO". This ensures that the logging level is restricted to these specific options, providing a controlled way to manage the verbosity of log output.
    
    log_json: bool = False

    # Safe default: only reachable from this machine.
    api_host: str = "127.0.0.1" #These specify where your API server should listen.
    api_port: int = Field(default=8000, ge=1, le=65535)

    @field_validator("ollama_base_url") #decorator written by pydantic library
    @classmethod 
    def _validate_base_url(cls, value: str) -> str: #this method is a class method that validates the value of the ollama_base_url setting. It checks if the value starts with "http://" or "https://". If it doesn't, it raises a ValueError. 
        #If the value is valid, it removes any trailing slashes from the URL and returns the cleaned value.
        if not value.startswith(("http://", "https://")):
            raise ValueError("must start with http:// or https://")
        return value.rstrip("/")


@lru_cache #lru_cache decorator means the function remembers the first settings object it creates and reuses it on subsequent calls.
def get_settings() -> Settings:
    return Settings()  # type: ignore[call-arg]